"use client";

import React, { useCallback, useEffect, useState } from "react";
import {
  AudioLines,
  FileText,
  Globe,
  Link2,
  Loader2,
  MoreHorizontal,
  Pencil,
  Plus,
  RefreshCw,
  Sparkles,
  Trash2,
  Type,
  UploadCloud,
} from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { ConfirmDialog, NameDialog } from "@/components/ui/confirm-dialog";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { DropZone } from "@/components/ui/drop-zone";
import { EmptyState } from "@/components/ui/empty-state";
import { Input } from "@/components/ui/input";
import { SegmentedControl } from "@/components/ui/segmented-control";
import { Skeleton } from "@/components/ui/skeleton";
import { Textarea } from "@/components/ui/textarea";
import { apiJson } from "@/lib/api";
import { cn } from "@/lib/utils";
import { VaultSource, VaultUploadResponse, Voice } from "@/types";

interface VoicesViewProps {
  voices: Voice[];
  isLoadingVoices: boolean;
  selectedVoice: Voice | null;
  onSelectVoice: (id: string) => void;
  onVoicesChanged: () => Promise<void>;
  getAccessToken: () => Promise<string | null>;
}

type InputMode = "file" | "text" | "url";

const sourceIcon = (type: VaultSource["source_type"]) =>
  type === "url" ? Globe : type === "text" ? Type : FileText;

const errorText = (err: unknown, fallback: string) => (err instanceof Error ? err.message : fallback);

export function VoicesView({
  voices,
  isLoadingVoices,
  selectedVoice,
  onSelectVoice,
  onVoicesChanged,
  getAccessToken,
}: VoicesViewProps) {
  const [mode, setMode] = useState<InputMode>("file");
  const [isBusy, setIsBusy] = useState(false);
  const [pastedTitle, setPastedTitle] = useState("");
  const [pastedText, setPastedText] = useState("");
  const [importUrl, setImportUrl] = useState("");
  const [sources, setSources] = useState<VaultSource[]>([]);
  const [isLoadingSources, setIsLoadingSources] = useState(false);
  const [isRefreshingProfile, setIsRefreshingProfile] = useState(false);

  const [createOpen, setCreateOpen] = useState(false);
  const [renameOpen, setRenameOpen] = useState(false);
  const [deleteVoiceOpen, setDeleteVoiceOpen] = useState(false);
  // Targets are captured when a dialog opens so its text stays stable during the close animation
  const [voiceToDelete, setVoiceToDelete] = useState<Voice | null>(null);
  const [sourceToDelete, setSourceToDelete] = useState<VaultSource | null>(null);
  const [deleteSourceOpen, setDeleteSourceOpen] = useState(false);

  const voiceId = selectedVoice?.id ?? null;

  const loadSources = useCallback(async () => {
    if (!voiceId) return setSources([]);
    setIsLoadingSources(true);
    try {
      setSources(await apiJson<VaultSource[]>(`/vault/sources?voice_id=${voiceId}`, await getAccessToken()));
    } catch (err) {
      toast.error(errorText(err, "Failed to load writing samples."));
    } finally {
      setIsLoadingSources(false);
    }
  }, [voiceId, getAccessToken]);

  useEffect(() => {
    loadSources();
  }, [loadSources]);

  /** Runs an ingest request, then refreshes samples and (after the background profile job) voices. */
  const ingest = async (request: (token: string | null) => Promise<VaultUploadResponse>) => {
    setIsBusy(true);
    const toastId = toast.loading("Analyzing your writing…");
    try {
      const data = await request(await getAccessToken());
      if (data.status !== "Success") throw new Error(data.message);
      toast.success(data.message, { id: toastId, description: "Your style profile will update in a few seconds." });
      await Promise.all([loadSources(), onVoicesChanged()]);
      // The style profile is regenerated by a background task on the server
      setTimeout(() => onVoicesChanged(), 6000);
      return true;
    } catch (err) {
      toast.error(errorText(err, "Upload failed."), { id: toastId });
      return false;
    } finally {
      setIsBusy(false);
    }
  };

  const handleFile = async (file: File) => {
    if (file.size > 10 * 1024 * 1024) return toast.error("File is too large. The maximum size is 10MB.");
    const formData = new FormData();
    formData.append("file", file);
    if (voiceId) formData.append("voice_id", voiceId);
    await ingest((token) => apiJson<VaultUploadResponse>("/vault/upload", token, { method: "POST", body: formData }));
  };

  const handleTextSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const ok = await ingest((token) =>
      apiJson<VaultUploadResponse>("/vault/text", token, {
        method: "POST",
        body: JSON.stringify({ title: pastedTitle.trim() || "Pasted text", text: pastedText, voice_id: voiceId }),
      }),
    );
    if (ok) {
      setPastedTitle("");
      setPastedText("");
    }
  };

  const handleUrlSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const ok = await ingest((token) =>
      apiJson<VaultUploadResponse>("/vault/url", token, {
        method: "POST",
        body: JSON.stringify({ url: importUrl, voice_id: voiceId }),
      }),
    );
    if (ok) setImportUrl("");
  };

  const deleteSource = async () => {
    if (!sourceToDelete) return;
    try {
      await apiJson(`/vault/sources/${sourceToDelete.id}`, await getAccessToken(), { method: "DELETE" });
      setSources((prev) => prev.filter((s) => s.id !== sourceToDelete.id));
      toast.success(`Removed "${sourceToDelete.name}"`);
      await onVoicesChanged();
      setTimeout(() => onVoicesChanged(), 6000);
    } catch (err) {
      toast.error(errorText(err, "Delete failed."));
    }
  };

  const createVoice = async (name: string) => {
    try {
      const voice = await apiJson<Voice>("/voices", await getAccessToken(), {
        method: "POST",
        body: JSON.stringify({ name }),
      });
      await onVoicesChanged();
      onSelectVoice(voice.id);
      toast.success(`Created "${name}"`);
    } catch (err) {
      toast.error(errorText(err, "Could not create voice."));
      throw err;
    }
  };

  const renameVoice = async (name: string) => {
    if (!selectedVoice) return;
    try {
      await apiJson(`/voices/${selectedVoice.id}`, await getAccessToken(), {
        method: "PATCH",
        body: JSON.stringify({ name }),
      });
      await onVoicesChanged();
    } catch (err) {
      toast.error(errorText(err, "Rename failed."));
      throw err;
    }
  };

  const deleteVoice = async () => {
    if (!voiceToDelete) return;
    try {
      await apiJson(`/voices/${voiceToDelete.id}`, await getAccessToken(), { method: "DELETE" });
      toast.success(`Deleted "${voiceToDelete.name}"`);
      await onVoicesChanged();
    } catch (err) {
      toast.error(errorText(err, "Delete failed."));
    }
  };

  const refreshProfile = async () => {
    if (!selectedVoice) return;
    setIsRefreshingProfile(true);
    try {
      await apiJson(`/voices/${selectedVoice.id}/profile`, await getAccessToken(), { method: "POST" });
      await onVoicesChanged();
      toast.success("Style profile updated");
    } catch (err) {
      toast.error(errorText(err, "Profile refresh failed."));
    } finally {
      setIsRefreshingProfile(false);
    }
  };

  return (
    <div className="grid items-start gap-6 lg:grid-cols-[260px_1fr]">
      {/* Voice list */}
      <aside className="grid gap-3 lg:sticky lg:top-6">
        <div className="flex items-center justify-between">
          <h2 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">Your voices</h2>
          <Button variant="ghost" size="icon-sm" onClick={() => setCreateOpen(true)} aria-label="New voice" title="New voice">
            <Plus />
          </Button>
        </div>

        {isLoadingVoices && voices.length === 0 ? (
          <div className="grid gap-2">
            {[0, 1].map((i) => (
              <Skeleton key={i} className="h-16 rounded-xl" />
            ))}
          </div>
        ) : (
          <div className="-mx-1 flex gap-2 overflow-x-auto px-1 pb-1 scrollbar-thin lg:mx-0 lg:grid lg:overflow-visible lg:px-0">
            {voices.map((voice) => {
              const active = voice.id === voiceId;
              return (
                <button
                  key={voice.id}
                  onClick={() => onSelectVoice(voice.id)}
                  aria-current={active ? "true" : undefined}
                  className={cn(
                    "flex min-w-[180px] items-center gap-3 rounded-xl border p-3 text-left transition-all focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring lg:min-w-0",
                    active ? "border-primary/40 bg-primary/5 ring-1 ring-primary/40" : "bg-card hover:border-foreground/20",
                  )}
                >
                  <span
                    className={cn(
                      "flex h-9 w-9 shrink-0 items-center justify-center rounded-lg",
                      active ? "bg-primary text-primary-foreground" : "bg-secondary text-muted-foreground",
                    )}
                  >
                    <AudioLines className="h-4 w-4" />
                  </span>
                  <span className="min-w-0">
                    <span className="block truncate text-sm font-medium">{voice.name}</span>
                    <span className="block text-xs text-muted-foreground">
                      {voice.source_count} sample{voice.source_count === 1 ? "" : "s"} · {voice.chunk_count} chunks
                    </span>
                  </span>
                </button>
              );
            })}
            <button
              onClick={() => setCreateOpen(true)}
              className="flex min-w-[140px] items-center justify-center gap-2 rounded-xl border border-dashed p-3 text-sm font-medium text-muted-foreground transition-colors hover:border-primary/50 hover:text-primary lg:min-w-0"
            >
              <Plus className="h-4 w-4" /> New voice
            </button>
          </div>
        )}
      </aside>

      {/* Voice detail */}
      {!selectedVoice ? (
        isLoadingVoices ? (
          <Skeleton className="h-96 rounded-2xl" />
        ) : (
          <EmptyState
            icon={AudioLines}
            title="Create your first voice"
            description="A voice learns from your past writing so generated content sounds like you."
            action={
              <Button onClick={() => setCreateOpen(true)}>
                <Plus /> New voice
              </Button>
            }
          />
        )
      ) : (
        <div className="grid min-w-0 gap-6">
          <div className="flex items-start justify-between gap-4">
            <div className="min-w-0">
              <h2 className="truncate text-2xl font-semibold tracking-tight">{selectedVoice.name}</h2>
              <p className="mt-1 text-sm text-muted-foreground">
                {selectedVoice.source_count} writing sample{selectedVoice.source_count === 1 ? "" : "s"} ·{" "}
                {selectedVoice.chunk_count} chunks indexed
              </p>
            </div>
            <DropdownMenu>
              <DropdownMenuTrigger asChild>
                <Button variant="outline" size="icon" aria-label="Voice actions">
                  <MoreHorizontal />
                </Button>
              </DropdownMenuTrigger>
              <DropdownMenuContent align="end" className="w-44 rounded-xl">
                <DropdownMenuItem onSelect={() => setRenameOpen(true)} className="gap-2">
                  <Pencil className="h-4 w-4" /> Rename
                </DropdownMenuItem>
                <DropdownMenuSeparator />
                <DropdownMenuItem
                  onSelect={() => {
                    setVoiceToDelete(selectedVoice);
                    setDeleteVoiceOpen(true);
                  }}
                  className="gap-2 text-destructive focus:text-destructive"
                >
                  <Trash2 className="h-4 w-4" /> Delete voice
                </DropdownMenuItem>
              </DropdownMenuContent>
            </DropdownMenu>
          </div>

          {/* Style profile */}
          <section className="relative overflow-hidden rounded-2xl border bg-card p-5 shadow-sm sm:p-6">
            <div className="absolute inset-x-0 top-0 h-1 bg-gradient-to-r from-primary via-fuchsia-500 to-pink-500" />
            <div className="mb-3 flex items-center justify-between gap-4">
              <h3 className="flex items-center gap-2 font-semibold">
                <Sparkles className="h-4 w-4 text-primary" /> Style profile
              </h3>
              <Button
                variant="ghost"
                size="sm"
                onClick={refreshProfile}
                disabled={isRefreshingProfile || selectedVoice.source_count === 0}
              >
                <RefreshCw className={cn(isRefreshingProfile && "animate-spin")} />
                Re-analyze
              </Button>
            </div>
            {selectedVoice.style_profile ? (
              <div className="whitespace-pre-line text-sm leading-relaxed text-muted-foreground">
                {selectedVoice.style_profile}
              </div>
            ) : selectedVoice.source_count === 0 ? (
              <p className="text-sm text-muted-foreground">
                Add a writing sample below and VoxScribe will summarize your tone, rhythm and signature phrases here.
              </p>
            ) : (
              <div className="grid gap-2">
                <Skeleton className="h-3.5 w-11/12" />
                <Skeleton className="h-3.5 w-9/12" />
                <Skeleton className="h-3.5 w-10/12" />
                <p className="mt-1 text-xs text-muted-foreground">Analyzing your writing…</p>
              </div>
            )}
          </section>

          {/* Add samples */}
          <section className="rounded-2xl border bg-card p-5 shadow-sm sm:p-6">
            <div className="mb-4 flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
              <div>
                <h3 className="font-semibold">Add writing samples</h3>
                <p className="text-sm text-muted-foreground">Articles, essays or newsletters you&apos;ve written.</p>
              </div>
              <SegmentedControl
                label="Sample type"
                size="sm"
                value={mode}
                onChange={setMode}
                options={[
                  { value: "file", label: "Upload", icon: UploadCloud },
                  { value: "text", label: "Paste", icon: Type },
                  { value: "url", label: "URL", icon: Link2 },
                ]}
              />
            </div>

            {mode === "file" && (
              <DropZone
                accept=".pdf,.docx,.txt,.md"
                onFile={handleFile}
                icon={UploadCloud}
                title="Click to upload or drag and drop"
                hint="PDF, DOCX, TXT or MD · up to 10MB"
                busy={isBusy}
                busyLabel="Analyzing your writing…"
              />
            )}

            {mode === "text" && (
              <form onSubmit={handleTextSubmit} className="grid gap-3">
                <Input
                  placeholder="Title (optional)"
                  aria-label="Sample title"
                  value={pastedTitle}
                  onChange={(e) => setPastedTitle(e.target.value)}
                  maxLength={200}
                />
                <Textarea
                  placeholder="Paste something you wrote (at least 50 characters)…"
                  aria-label="Sample text"
                  value={pastedText}
                  onChange={(e) => setPastedText(e.target.value)}
                  rows={7}
                  required
                  className="resize-y"
                />
                <div className="flex items-center justify-between">
                  <span className="text-xs tabular-nums text-muted-foreground">
                    {pastedText.trim().length.toLocaleString()} characters
                  </span>
                  <Button type="submit" disabled={isBusy || pastedText.trim().length < 50}>
                    {isBusy && <Loader2 className="animate-spin" />}
                    Add to voice
                  </Button>
                </div>
              </form>
            )}

            {mode === "url" && (
              <form onSubmit={handleUrlSubmit} className="flex flex-col gap-2 sm:flex-row">
                <Input
                  type="url"
                  placeholder="https://yourblog.com/a-post-you-wrote"
                  aria-label="Article URL"
                  value={importUrl}
                  onChange={(e) => setImportUrl(e.target.value)}
                  required
                />
                <Button type="submit" disabled={isBusy} className="h-10 shrink-0">
                  {isBusy && <Loader2 className="animate-spin" />}
                  Import
                </Button>
              </form>
            )}
          </section>

          {/* Samples */}
          <section>
            <h3 className="mb-3 text-xs font-semibold uppercase tracking-wider text-muted-foreground">Writing samples</h3>
            {isLoadingSources && sources.length === 0 ? (
              <div className="grid gap-2">
                {[0, 1, 2].map((i) => (
                  <Skeleton key={i} className="h-14 rounded-xl" />
                ))}
              </div>
            ) : sources.length === 0 ? (
              <EmptyState
                icon={FileText}
                title="No samples yet"
                description="Add at least one sample so VoxScribe can learn how you write."
                className="py-10"
              />
            ) : (
              <ul className="divide-y overflow-hidden rounded-2xl border bg-card">
                {sources.map((source) => {
                  const Icon = sourceIcon(source.source_type);
                  return (
                    <li key={source.id} className="group flex items-center gap-3 px-4 py-3 transition-colors hover:bg-secondary/40">
                      <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-secondary text-muted-foreground">
                        <Icon className="h-4 w-4" />
                      </span>
                      <div className="min-w-0 flex-1">
                        <p className="truncate text-sm font-medium">{source.name}</p>
                        <p className="text-xs text-muted-foreground">
                          {source.source_type.toUpperCase()} · {source.chunk_count} chunks ·{" "}
                          {new Date(source.created_at).toLocaleDateString(undefined, { month: "short", day: "numeric" })}
                        </p>
                      </div>
                      <Button
                        variant="ghost"
                        size="icon-sm"
                        onClick={() => {
                          setSourceToDelete(source);
                          setDeleteSourceOpen(true);
                        }}
                        aria-label={`Remove ${source.name}`}
                        className="opacity-100 hover:text-destructive sm:opacity-0 sm:group-hover:opacity-100 sm:focus-visible:opacity-100"
                      >
                        <Trash2 />
                      </Button>
                    </li>
                  );
                })}
              </ul>
            )}
          </section>
        </div>
      )}

      <NameDialog
        open={createOpen}
        onOpenChange={setCreateOpen}
        title="New voice"
        description="Create separate voices for different brands or audiences."
        placeholder='e.g. "Company blog"'
        submitLabel="Create voice"
        onSubmit={createVoice}
      />
      <NameDialog
        open={renameOpen}
        onOpenChange={setRenameOpen}
        title="Rename voice"
        initialValue={selectedVoice?.name ?? ""}
        onSubmit={renameVoice}
      />
      <ConfirmDialog
        open={deleteVoiceOpen}
        onOpenChange={setDeleteVoiceOpen}
        title={`Delete "${voiceToDelete?.name ?? ""}"?`}
        description={`This permanently removes the voice and all ${voiceToDelete?.source_count ?? 0} of its writing samples.`}
        confirmLabel="Delete voice"
        destructive
        onConfirm={deleteVoice}
      />
      <ConfirmDialog
        open={deleteSourceOpen}
        onOpenChange={setDeleteSourceOpen}
        title="Remove writing sample?"
        description={`"${sourceToDelete?.name ?? ""}" will no longer influence this voice.`}
        confirmLabel="Remove"
        destructive
        onConfirm={deleteSource}
      />
    </div>
  );
}
